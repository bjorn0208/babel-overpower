-- ============================================
-- 1. TABELAS
-- ============================================

CREATE TABLE IF NOT EXISTS public_profile (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{3,40}$'),
  is_active boolean NOT NULL DEFAULT false,
  agent_enabled boolean NOT NULL DEFAULT true,
  cta_texto text DEFAULT 'Fale agora',
  cta_tipo text DEFAULT 'chat' CHECK (cta_tipo IN ('chat','whatsapp')),
  video_youtube_url text,
  youtube_canal_url text,
  show_agent_online_badge boolean NOT NULL DEFAULT true,
  headline text,
  subheadline text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public_services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  nome text NOT NULL,
  descricao text,
  foto_url text,
  preco_text text,
  ordem integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_services_user_ordem
  ON public_services(user_id, ordem);

CREATE TABLE IF NOT EXISTS public_gallery (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  titulo text,
  descricao text,
  foto_url text NOT NULL,
  ordem integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_gallery_user_ordem
  ON public_gallery(user_id, ordem);

CREATE TABLE IF NOT EXISTS public_testimonials (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  autor_nome text NOT NULL,
  autor_foto_url text,
  texto text NOT NULL,
  nota smallint CHECK (nota BETWEEN 1 AND 5),
  aprovado boolean NOT NULL DEFAULT false,
  aprovado_at timestamptz,
  rag_chunk_id uuid REFERENCES knowledge_chunks(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_testimonials_user_aprovado
  ON public_testimonials(user_id, aprovado, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_public_testimonials_rag_chunk
  ON public_testimonials(rag_chunk_id) WHERE rag_chunk_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public_chat_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  session_token uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  lead_id uuid REFERENCES leads(id) ON DELETE SET NULL,
  conversation_id uuid REFERENCES conversations(id) ON DELETE SET NULL,
  visitor_name text,
  visitor_phone text,
  visitor_email text,
  ip_hash text,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_activity_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_chat_sessions_user_activity
  ON public_chat_sessions(user_id, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_public_chat_sessions_lead
  ON public_chat_sessions(lead_id) WHERE lead_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_public_chat_sessions_conversation
  ON public_chat_sessions(conversation_id) WHERE conversation_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public_profile_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  session_id uuid,
  event_type text NOT NULL CHECK (event_type IN (
    'page_view','cta_click','chat_started','chat_message',
    'lead_created','whatsapp_handoff','testimonial_submitted'
  )),
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_public_profile_events_user_type_created
  ON public_profile_events(user_id, event_type, created_at DESC);

