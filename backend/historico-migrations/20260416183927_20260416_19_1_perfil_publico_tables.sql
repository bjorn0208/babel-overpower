-- ============================================
-- 5. Função de leitura pública (SECURITY DEFINER)
-- ============================================

CREATE OR REPLACE FUNCTION public_get_profile(p_slug text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path = public, auth
AS $$
DECLARE
  v_user_id uuid;
  v_profile jsonb;
  v_empresa jsonb;
  v_services jsonb;
  v_gallery jsonb;
  v_testimonials jsonb;
BEGIN
  SELECT pp.user_id INTO v_user_id
  FROM public_profile pp
  WHERE pp.slug = p_slug AND pp.is_active = true;

  IF v_user_id IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT to_jsonb(pp) - 'user_id' INTO v_profile
  FROM public_profile pp WHERE pp.user_id = v_user_id;

  SELECT jsonb_build_object(
    'nome', e.nome,
    'descricao', e.descricao,
    'endereco', e.endereco,
    'bairro', e.bairro,
    'cidade', e.cidade,
    'estado', e.estado,
    'cep', e.cep,
    'instagram', e.instagram,
    'facebook', e.facebook,
    'tiktok', e.tiktok,
    'whatsapp', e.whatsapp,
    'youtube', e.youtube,
    'site', e.site,
    'logo_url', e.logo_url,
    'banner_url', e.banner_url
  ) INTO v_empresa
  FROM empresas e WHERE e.user_id = v_user_id LIMIT 1;

  SELECT coalesce(jsonb_agg(
    jsonb_build_object(
      'id', s.id, 'nome', s.nome, 'descricao', s.descricao,
      'foto_url', s.foto_url, 'preco_text', s.preco_text, 'ordem', s.ordem
    ) ORDER BY s.ordem
  ), '[]'::jsonb) INTO v_services
  FROM public_services s WHERE s.user_id = v_user_id;

  SELECT coalesce(jsonb_agg(
    jsonb_build_object(
      'id', g.id, 'titulo', g.titulo, 'descricao', g.descricao,
      'foto_url', g.foto_url, 'ordem', g.ordem
    ) ORDER BY g.ordem
  ), '[]'::jsonb) INTO v_gallery
  FROM public_gallery g WHERE g.user_id = v_user_id;

  SELECT coalesce(jsonb_agg(
    jsonb_build_object(
      'id', t.id, 'autor_nome', t.autor_nome, 'autor_foto_url', t.autor_foto_url,
      'texto', t.texto, 'nota', t.nota, 'created_at', t.created_at
    ) ORDER BY t.created_at DESC
  ), '[]'::jsonb) INTO v_testimonials
  FROM public_testimonials t
  WHERE t.user_id = v_user_id AND t.aprovado = true;

  RETURN jsonb_build_object(
    'profile', v_profile,
    'empresa', v_empresa,
    'services', v_services,
    'gallery', v_gallery,
    'testimonials', v_testimonials
  );
END;
$$;

REVOKE ALL ON FUNCTION public_get_profile(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public_get_profile(text) TO anon, authenticated;

-- ============================================
-- 6. Trigger testimonial → knowledge_chunks (RAG)
-- ============================================

CREATE OR REPLACE FUNCTION public_testimonial_to_rag()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_agent_id uuid;
  v_chunk_id uuid;
  v_content text;
BEGIN
  -- Aprovou: cria chunk
  IF NEW.aprovado = true
     AND (TG_OP = 'INSERT' OR OLD.aprovado = false)
     AND NEW.rag_chunk_id IS NULL
  THEN
    SELECT id INTO v_agent_id
    FROM user_agents
    WHERE user_id = NEW.user_id AND is_active = true
    ORDER BY created_at DESC LIMIT 1;

    IF v_agent_id IS NOT NULL THEN
      v_content := NEW.autor_nome
        || CASE WHEN NEW.nota IS NOT NULL THEN ' (' || NEW.nota || '★)' ELSE '' END
        || ': ' || NEW.texto;

      INSERT INTO knowledge_chunks (agent_id, title, content, category, escopo, tipo, ativo)
      VALUES (
        v_agent_id,
        'Depoimento de ' || NEW.autor_nome,
        v_content,
        'prova_social',
        'tenant',
        'resposta_factual',
        true
      ) RETURNING id INTO v_chunk_id;

      NEW.rag_chunk_id := v_chunk_id;
      NEW.aprovado_at := now();
    END IF;
  END IF;

  -- Reprovou: remove chunk
  IF TG_OP = 'UPDATE'
     AND NEW.aprovado = false
     AND OLD.aprovado = true
     AND OLD.rag_chunk_id IS NOT NULL
  THEN
    DELETE FROM knowledge_chunks WHERE id = OLD.rag_chunk_id;
    NEW.rag_chunk_id := NULL;
    NEW.aprovado_at := NULL;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tg_public_testimonial_to_rag ON public_testimonials;
CREATE TRIGGER tg_public_testimonial_to_rag
BEFORE INSERT OR UPDATE ON public_testimonials
FOR EACH ROW EXECUTE FUNCTION public_testimonial_to_rag();

-- Delete em cascata manual: se deletar testimonial, deleta o chunk RAG
CREATE OR REPLACE FUNCTION public_testimonial_delete_rag()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF OLD.rag_chunk_id IS NOT NULL THEN
    DELETE FROM knowledge_chunks WHERE id = OLD.rag_chunk_id;
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS tg_public_testimonial_delete_rag ON public_testimonials;
CREATE TRIGGER tg_public_testimonial_delete_rag
AFTER DELETE ON public_testimonials
FOR EACH ROW EXECUTE FUNCTION public_testimonial_delete_rag();

