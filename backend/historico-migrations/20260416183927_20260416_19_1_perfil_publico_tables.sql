-- e sempre com aprovado=false (moderação obrigatória)
DROP POLICY IF EXISTS "anon_insert_public_testimonials" ON public_testimonials;
CREATE POLICY "anon_insert_public_testimonials" ON public_testimonials
  FOR INSERT TO anon
  WITH CHECK (
    aprovado = false
    AND aprovado_at IS NULL
    AND rag_chunk_id IS NULL
    AND EXISTS (
      SELECT 1 FROM public_profile pp
      WHERE pp.user_id = public_testimonials.user_id AND pp.is_active = true
    )
  );

